#!/usr/bin/env python3
"""Generate compact POI vector coverage; no runtime geometry or font dependency."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rounded(x, y, left, top, right, bottom, radius):
    if not (left <= x <= right and top <= y <= bottom):
        return False
    cx = max(left + radius, min(right - radius, x))
    cy = max(top + radius, min(bottom - radius, y))
    return (x - cx)**2 + (y - cy)**2 <= radius**2


def line(x, y, a, b, radius):
    dx, dy = b[0] - a[0], b[1] - a[1]
    t = max(0, min(1, ((x-a[0])*dx + (y-a[1])*dy)/(dx*dx+dy*dy)))
    return (x-a[0]-t*dx)**2 + (y-a[1]-t*dy)**2 <= radius**2


def symbol(kind, x, y):
    if kind == 0:  # Fuel pump, window cutout and separate hose/nozzle.
        body = rounded(x,y,4,3.3,9.5,12.2,.9) and not rounded(x,y,5.4,4.7,8.1,7.1,.3)
        base = rounded(x,y,3.3,11.8,10.2,13,.5)
        path = ((9.3,6.3),(11,7),(11,10.4),(12.7,10.4),(12.7,6),(11,4.1))
        return body or base or any(line(x,y,a,b,.6) for a,b in zip(path,path[1:]))
    if kind == 1:  # Parking P, independent of UI font metrics.
        stem = rounded(x,y,4.8,3.5,6.7,12.7,.5)
        bowl = rounded(x,y,4.8,3.5,11.6,9.4,2) and not rounded(x,y,6.5,5.2,9.9,7.7,.6)
        return stem or bowl
    return rounded(x,y,6.5,3.4,9.5,12.6,.5) or rounded(x,y,3.4,6.5,12.6,9.5,.5)


def coverage(shape):
    result = []
    for y in range(16):
        for x in range(16):
            count = sum(shape(x+(sx+.5)/8,y+(sy+.5)/8) for sy in range(8) for sx in range(8))
            result.append((count*15+32)//64)
    return result


def main():
    outer = lambda x,y: rounded(x,y,.5,.5,15.5,15.5,4.5)
    inner = lambda x,y: rounded(x,y,1.5,1.5,14.5,14.5,3.5)
    masks = [coverage(outer), coverage(lambda x,y: outer(x,y) and not inner(x,y))]
    masks += [coverage(lambda x,y,k=k: symbol(k,x,y)) for k in range(3)]
    rows = ['/* Generated by tools/build_poi_icons.py: 16x16, 8x8 supersampling. */',
            'static const u8 poi_coverage[5][256]={']
    for mask in masks:
        rows.append(' {')
        rows += ['  '+','.join(map(str,mask[y*16:(y+1)*16]))+',' for y in range(16)]
        rows.append(' },')
    rows.append('};')
    (ROOT/'clio843/src/poi_icons.h').write_text('\n'.join(rows)+'\n')


if __name__ == '__main__':
    main()
