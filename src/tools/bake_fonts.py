#!/usr/bin/env python3
"""Bake licensed proportional text into four-bit coverage masks for integer C drawing."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
HERE=Path(__file__).resolve().parents[1]
ROLES=[(11,False),(13,False),(15,False),(15,True),(18,True),(24,True),(32,True)]
CHARS=list(range(32,127))+[176,8226,8230]

def main():
 data=[];glyphs=[]
 for size,bold in ROLES:
  font=ImageFont.truetype(str(HERE/'fonts'/('VeraBd.ttf' if bold else 'Vera.ttf')),size)
  for code in CHARS:
   ch=chr(code);bounds=font.getbbox(ch);left,top,right,bottom=bounds
   w=max(0,right-left);h=max(0,bottom-top);advance=round(font.getlength(ch))
   mask=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(mask).text((-left,-top),ch,font=font,fill=255)
   pixels=mask.get_flattened_data() if hasattr(mask,"get_flattened_data") else mask.getdata()
   values=[round(a/17) for a in pixels] if w*h else []
   offset=len(data)
   for i in range(0,len(values),2):data.append(values[i]|((values[i+1] if i+1<len(values) else 0)<<4))
   glyphs.append((offset,w,h,left,top,advance))
 target=HERE/'clio843/src/font_atlas.h';target.parent.mkdir(exist_ok=True)
 with target.open('w') as out:
  out.write('/* Bitstream Vera glyph masks. See ../../fonts/LICENSE.txt. Generated by bake_fonts.py. */\n')
  out.write('struct CpGlyph {u32 off;u8 w,h; signed char left,top;u8 advance;};\n')
  out.write('static const struct CpGlyph cp_glyphs[]={\n'+',\n'.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'\n};\n')
  out.write('static const u8 cp_alpha[]={\n')
  for i in range(0,len(data),32):out.write(','.join(map(str,data[i:i+32]))+',\n')
  out.write('};\n')
 print('Font atlas:',len(data),'coverage bytes;',len(glyphs),'glyph metrics')
if __name__=='__main__':main()
