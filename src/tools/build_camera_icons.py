#!/usr/bin/env python3
"""Generate compact supersampled camera map-badge and HUD icons."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rounded(x, y, left, top, right, bottom, radius):
    if not (left <= x <= right and top <= y <= bottom):
        return False
    cx = max(left + radius, min(right - radius, x))
    cy = max(top + radius, min(bottom - radius, y))
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2


def circle(x, y, cx, cy, r):
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def symbol(kind, u, v):
    if kind == 0:  # Fixed speed camera: compact body, top hood and ringed lens.
        body = rounded(u, v, 0.10, 0.27, 0.90, 0.83, 0.13)
        hood = rounded(u, v, 0.30, 0.14, 0.70, 0.34, 0.08)
        ring = circle(u, v, 0.50, 0.55, 0.20)
        pupil = circle(u, v, 0.50, 0.55, 0.095)
        return ((body or hood) and not ring) or pupil
    if kind == 1:  # Red-light camera: vertical traffic signal housing with 3 lamps.
        body = rounded(u, v, 0.25, 0.06, 0.75, 0.94, 0.16)
        lamps = (
            circle(u, v, 0.50, 0.25, 0.112)
            or circle(u, v, 0.50, 0.50, 0.112)
            or circle(u, v, 0.50, 0.75, 0.112)
        )
        return body and not lamps
    # Average-speed check: twin staggered speed cameras (paired section cameras).
    front_outer = rounded(u, v, 0.24, 0.36, 0.96, 0.88, 0.13) or rounded(u, v, 0.42, 0.24, 0.78, 0.42, 0.08)
    front_gap = rounded(u, v, 0.16, 0.28, 0.98, 0.94, 0.16) or rounded(u, v, 0.34, 0.16, 0.84, 0.44, 0.10)
    front = front_outer and not circle(u, v, 0.60, 0.62, 0.16) or circle(u, v, 0.60, 0.62, 0.07)
    back = (rounded(u, v, 0.04, 0.20, 0.68, 0.68, 0.12) or rounded(u, v, 0.19, 0.09, 0.51, 0.26, 0.07)) and not front_gap
    return front or back


def red_lamp(u, v):
    return circle(u, v, 0.50, 0.25, 0.095)


def coverage(size, shape):
    result = []
    for y in range(size):
        for x in range(size):
            count = sum(
                shape(x + (sx + 0.5) / 8, y + (sy + 0.5) / 8)
                for sy in range(8)
                for sx in range(8)
            )
            result.append((count * 15 + 32) // 64)
    return result


def emit_array(name, size, masks):
    rows = [f'static const u8 {name}[{len(masks)}][{size * size}]={{']
    for mask in masks:
        rows.append(' {')
        rows += ['  ' + ','.join(map(str, mask[y * size:(y + 1) * size])) + ',' for y in range(size)]
        rows.append(' },')
    rows.append('};')
    return rows


def main():
    outer = lambda x, y: rounded(x, y, 0.5, 0.5, 17.5, 17.5, 5.2)
    inner = lambda x, y: rounded(x, y, 1.8, 1.8, 16.2, 16.2, 3.9)
    badge_u = lambda x: (x - 3.0) / 12.0
    badge_v = lambda y: (y - 3.0) / 12.0
    badge_masks = [
        coverage(18, outer),
        coverage(18, lambda x, y: outer(x, y) and not inner(x, y)),
    ]
    badge_masks += [
        coverage(18, lambda x, y, k=k: symbol(k, badge_u(x), badge_v(y)))
        for k in range(3)
    ]
    badge_masks.append(coverage(18, lambda x, y: red_lamp(badge_u(x), badge_v(y))))

    hud_u = lambda x: (x - 0.5) / 13.0
    hud_v = lambda y: (y - 0.5) / 13.0
    hud_masks = [
        coverage(14, lambda x, y, k=k: symbol(k, hud_u(x), hud_v(y)))
        for k in range(3)
    ]
    hud_masks.append(coverage(14, lambda x, y: red_lamp(hud_u(x), hud_v(y))))

    rows = [
        '/* Generated by tools/build_camera_icons.py: 8x8 supersampling. */',
        '/* Badge indices: 0=backing, 1=rim, 2=fixed, 3=red-light, 4=average, 5=red-lamp. */',
        *emit_array('cam_badge_coverage', 18, badge_masks),
        '/* HUD indices: 0=fixed, 1=red-light, 2=average, 3=red-lamp. */',
        *emit_array('cam_hud_coverage', 14, hud_masks),
    ]
    (ROOT / 'clio843/src/camera_icons.h').write_text('\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
