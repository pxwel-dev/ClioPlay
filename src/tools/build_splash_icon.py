#!/usr/bin/env python3
"""Precompute 8x8 coverage for the existing procedural splash icon.

Only edges need fractional coverage; the head unit draws one 72px icon without
allocating an enlarged framebuffer or supersampling during boot.
"""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SIZE=72
SAMPLES=8

def masks():
 outer=[];arrow=[];scale=2*SAMPLES;extent=SIZE*scale;radius=19*scale
 for y in range(SIZE):
  for x in range(SIZE):
   a=b=0
   for sy in range(SAMPLES):
    for sx in range(SAMPLES):
     xx=x*scale+2*sx+1;yy=y*scale+2*sy+1
     dx=max(radius-xx,0,xx-(extent-radius));dy=max(radius-yy,0,yy-(extent-radius))
     inside=dx*dx+dy*dy<=radius*radius
     ax=abs(xx-extent//2);ay=yy-extent//2
     mark=(-22*scale<=ay<=22*scale and ax*44<=(ay+22*scale)*19 and (ay<=10*scale or ax*3>=(ay-10*scale)*6))
     a+=inside;b+=inside and mark
   outer.append(a);arrow.append(b)
 return outer,arrow

def main():
 outer,arrow=masks()
 assert all(0<=b<=a<=64 for a,b in zip(outer,arrow))
 text='/* Generated by tools/build_splash_icon.py: 8x8 subpixel coverage, 0..64. */\n'
 text+='enum { SPL_ICON_SIZE=72 };\n'
 for name,values in [('outer',outer),('arrow',arrow)]:
  text+='static const u8 spl_icon_'+name+'[72*72]={\n'
  text+=''.join(' '+','.join(map(str,values[y*SIZE:(y+1)*SIZE]))+',\n' for y in range(SIZE))+'};\n'
 path=ROOT/'clio843/src/splash_icon.h'
 if not path.exists() or path.read_text()!=text:path.write_text(text)
if __name__=='__main__':main()
