#!/usr/bin/env python3
"""Build antialiased directional vehicle coverage, without runtime rasterisation."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
SIZE, HEADINGS, SAMPLES = 28, 36, 8


def arrow(x, y, scale=1):
    x, y = abs(x / scale), y / scale
    return x <= 9 and -12 + 21*x/9 <= y <= 5 + 4*x/9


def masks():
    result = []
    for heading in range(HEADINGS):
        angle = math.radians(heading*10)
        sine, cosine = math.sin(angle), math.cos(angle)
        pixels = []
        for y in range(SIZE):
            for x in range(SIZE):
                counts = [0, 0, 0, 0]
                for sy in range(SAMPLES):
                    for sx in range(SAMPLES):
                        dx = x - SIZE/2 + (sx+.5)/SAMPLES
                        dy = y - SIZE/2 + (sy+.5)/SAMPLES
                        lx, ly = dx*cosine + dy*sine, -dx*sine + dy*cosine
                        # Shadow remains below the pointer at every heading.
                        shadow_y = dy - 1.2
                        shadow = arrow(dx*cosine + shadow_y*sine,
                                       -dx*sine + shadow_y*cosine, 1.04)
                        outer, inner = arrow(lx, ly), arrow(lx, ly, .78)
                        for layer, value in enumerate((shadow, outer, inner, inner and lx < 0)):
                            counts[layer] += value
                # Four nibble masks: soft shadow, pale shell, blue body, facet.
                alpha = [(count*maximum+32)//64 for count, maximum in zip(counts, (5,15,15,5))]
                pixels.append(sum(a << (layer*4) for layer, a in enumerate(alpha)))
        result.append(pixels)
    return result


def main():
    rows = ['/* Generated by tools/build_vehicle_icon.py: 28x28, 36 headings, 8x8 AA. */',
            '#define VEHICLE_ICON_SIZE 28', '#define VEHICLE_ICON_HEADINGS 36',
            'static const u16 vehicle_coverage[VEHICLE_ICON_HEADINGS][VEHICLE_ICON_SIZE*VEHICLE_ICON_SIZE]={']
    for pixels in masks():
        rows.append(' {')
        rows += ['  '+','.join(f'0x{v:04x}' for v in pixels[y*SIZE:(y+1)*SIZE])+',' for y in range(SIZE)]
        rows.append(' },')
    rows.append('};')
    (ROOT/'clio843/src/vehicle_icon.h').write_text('\n'.join(rows)+'\n')


if __name__ == '__main__':
    main()
