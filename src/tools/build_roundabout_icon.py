#!/usr/bin/env python3
"""Generate the compact roundabout circulation glyph with 8x8 edge coverage."""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def segment_distance(x, y, ax, ay, bx, by):
    dx, dy = bx-ax, by-ay
    t = max(0., min(1., ((x-ax)*dx+(y-ay)*dy)/(dx*dx+dy*dy)))
    return math.hypot(x-ax-t*dx, y-ay-t*dy)


def inside(x, y):
    # Clockwise path: enter from below, circulate on the left and over the top,
    # then point down at the right. Mirroring the mask reverses circulation.
    r, cy, half = 7.5, -1.5, 1.1
    angle = math.atan2(x, -(y-cy)) % (2*math.pi)
    arc = abs(math.hypot(x, y-cy)-r) <= half and (angle >= math.pi or angle <= math.pi/2)
    stem = segment_distance(x, y, 0, 6., 0, 10.) <= half
    # Filled tangent arrow, separated from the numeral's central clear area.
    ax, ay, bx, by, cx, ty = 5.3, -2.7, 10.9, -2.7, 8.1, 3.0
    a=(bx-ax)*(y-ay)-(by-ay)*(x-ax)
    b=(cx-bx)*(y-by)-(ty-by)*(x-bx)
    c=(ax-cx)*(y-ty)-(ay-ty)*(x-cx)
    arrow = (a >= 0 and b >= 0 and c >= 0) or (a <= 0 and b <= 0 and c <= 0)
    return arc or stem or arrow


def main():
    pixels=[]
    for y in range(-11,12):
        for x in range(-11,12):
            count=sum(inside(x+(sx+.5)/8-.5, y+(sy+.5)/8-.5) for sy in range(8) for sx in range(8))
            pixels.append((count*15+32)//64)
    text=('/* Generated by tools/build_roundabout_icon.py. Original 23x23 clockwise\n'
          ' * glyph, 4-bit alpha; mirror horizontally for right-hand traffic.\n'
          ' * 529 read-only bytes; no device geometry, trig or scratch buffer. */\n'
          'static const u8 nav_roundabout_alpha[23*23]={\n')
    text+=''.join(' '+','.join(map(str,pixels[i:i+23]))+',\n' for i in range(0,len(pixels),23))+'};\n'
    # Narrow two-digit counts derive from the existing licensed Vera atlas;
    # resample at build time so uncommon exits >=10 never become an ellipsis.
    atlas=(ROOT/'clio843/src/font_atlas.h').read_text()
    glyphs=[tuple(map(int,m.split(','))) for m in re.findall(r'\{([0-9, -]+)\}',atlas.split('static const u8 cp_alpha')[0])]
    alpha=list(map(int,re.findall(r'\d+',atlas.split('static const u8 cp_alpha[]={',1)[1].split('};',1)[0])))
    digits=[]
    for digit in range(10):
        off,w,h,_,_,_=glyphs[ord('0')+digit-32]
        assert (w,h)==(7,8)
        mask=[]
        for y in range(7):
            for x in range(5):
                weighted=0
                for sy in range(8):
                    wy=max(0,min((y+1)*8,(sy+1)*7)-max(y*8,sy*7))
                    for sx in range(7):
                        wx=max(0,min((x+1)*7,(sx+1)*5)-max(x*7,sx*5))
                        n=sy*w+sx;a=(alpha[off+n//2]>>((n&1)*4))&15
                        weighted+=a*wx*wy
                mask.append((weighted+28)//56)
        digits.append(mask)
    text+='/* Narrow Vera digit masks; see ../../fonts/LICENSE.txt. */\n'
    text+='static const u8 nav_roundabout_digits[10][35]={\n'
    text+=''.join(' {'+','.join(map(str,m))+'},\n' for m in digits)+'};\n'
    (ROOT/'clio843/src/nav_roundabout.h').write_text(text)


if __name__ == '__main__':
    main()
