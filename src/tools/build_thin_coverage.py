#!/usr/bin/env python3
"""Generate pixel-area coverage and a softer reconstruction filter for minor roads."""
import math
from pathlib import Path


def coverage(slope, distance):
    # Average the band's overlap with a pixel over its full major-axis width.
    half = math.sqrt(1 + slope * slope) / 2
    def edge(t):
        if not slope:
            return max(0., min(1., t + .5))
        a, b = t + .5 - slope / 2, t + .5 + slope / 2
        def primitive(v):
            return 0. if v <= 0 else v - .5 if v >= 1 else v * v / 2
        return (primitive(b) - primitive(a)) / slope
    return max(0., min(1., edge(half - distance) - edge(-half - distance)))


def soft_coverage(slope, distance):
    # A 1.2 px stroke reconstructed with an isotropic Gaussian (sigma .55 px).
    # The gentle width increase compensates for the softer core on RGB565.
    distance /= math.sqrt(1 + slope * slope)
    scale = .55 * math.sqrt(2)
    return .5 * (math.erf((distance + .6) / scale) - math.erf((distance - .6) / scale))


def main():
    rows = [[int(coverage(i / 32, j / 64) * 32 + .5) for j in range(113)] for i in range(33)]
    source = ('/* Generated by tools/build_thin_coverage.py. Pixel-area coverage, not\n'
              ' * centre-column coverage: slopes 0..1 /32, distances 0..1.75 /64.\n'
              ' * 3,729 read-only bytes; no runtime division or supersampled buffer. */\n'
              'static const u8 map_thin_coverage[33][113]={\n')
    source += ''.join(' {' + ','.join(map(str, row)) + '},\n' for row in rows) + '};\n'
    source += ('/* Minor roads only: isotropic Gaussian reconstruction, sigma .55 px,\n'
               ' * nominal width 1.2 px. Body distance /64; cap squared distance /128.\n'
               ' * Prequantised to the 5-bit road mask. Text/routes/wider roads stay sharp. */\n')
    soft = [[int(soft_coverage(i / 32, j / 64) * 32 + .5) for j in range(177)] for i in range(33)]
    pack = lambda a: (a * 31 + 16) >> 5
    soft = [[pack(a) for a in row] for row in soft]
    source += 'static const u8 map_minor_coverage[33][177]={\n'
    source += ''.join(' {' + ','.join(map(str, row)) + '},\n' for row in soft) + '};\n'
    radius = [max(j for j, a in enumerate(row) if a) for row in soft]
    source += 'static const u8 map_minor_radius[33]={' + ','.join(map(str, radius)) + '};\n'
    caps = [pack(int(soft_coverage(0, math.sqrt(j / 128)) * 32 + .5)) for j in range(1025)]
    source += 'static const u8 map_minor_caps[1025]={\n'
    source += ''.join(' ' + ','.join(map(str, caps[i:i+32])) + ',\n' for i in range(0, len(caps), 32)) + '};\n'
    (Path(__file__).resolve().parents[1] / 'clio843/src/map_thin_coverage.h').write_text(source)


if __name__ == '__main__':
    main()
