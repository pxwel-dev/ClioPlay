#!/usr/bin/env python3
"""Bake keyboard layouts and the bundled Unicode 17 Pinyin character readings.

Regular builds use the supplied header and need no download. To reproduce the
Pinyin table: --unihan Unihan.zip or --download (verified, temporary download).
"""
import argparse,hashlib,json,re,tempfile,unicodedata,urllib.request,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'clio843/src/keyboard-data'
URL='https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip'
SHA='f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e'
def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def roman(s):
 s=s.lower().replace('ü','v');s=unicodedata.normalize('NFD',s).replace('u\u0308','v')
 return ''.join(c for c in s if 'a'<=c<='z')
def pinyin(archive):
 if digest(archive)!=SHA:raise ValueError('Unexpected Unihan archive checksum')
 readings={};frequency={}
 with zipfile.ZipFile(archive) as z:
  for line in z.read('Unihan_Readings.txt').decode().splitlines():
   if not line or line[0]=='#':continue
   char,field,value=line.split('\t',2);cp=int(char[2:],16)
   if not 0x3400<=cp<=0x9fff:continue
   if field=='kMandarin':
    for syllable in value.split():readings.setdefault(roman(syllable),set()).add(cp)
   elif field=='kHanyuPinlu':
    for syllable,n in re.findall(r'([^\s()]+)\((\d+)\)',value):
     r=roman(syllable);readings.setdefault(r,set()).add(cp);frequency[r,cp]=frequency.get((r,cp),0)+int(n)
 rows=[]
 for syllable,chars in sorted(readings.items()):
  if not re.fullmatch('[a-z]{1,8}',syllable):continue
  ordered=sorted(chars,key=lambda cp:(-frequency.get((syllable,cp),0),cp))
  rows.append(' {'+json.dumps(syllable)+','+json.dumps(''.join(map(chr,ordered)),ensure_ascii=False)+'},')
 header=DATA/'pinyin.h';header.write_text('/* Unicode 17.0.0 Unihan kMandarin/kHanyuPinlu, Unicode-3.0.\n * See UNICODE-LICENSE.txt and pinyin.json; generated by build_keyboard_data.py. */\nstruct KbdPinyinRow {const char*syllable;const char*characters;};\nstatic const struct KbdPinyinRow kbd_pinyin_rows[]={\n'+'\n'.join(rows)+'\n};\n')
 (DATA/'pinyin.json').write_text(json.dumps({'unicode':'17.0.0','source':URL,'source_sha256':SHA,'properties':['kMandarin','kHanyuPinlu'],'range':'U+3400..U+9FFF','syllables':len(rows),'licence':'Unicode-3.0','header_sha256':digest(header)},indent=2)+'\n')
def main(argv=None):
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--unihan',type=Path);p.add_argument('--download',action='store_true');a=p.parse_args(argv)
 DATA.mkdir(exist_ok=True)
 if a.unihan:pinyin(a.unihan)
 elif a.download:
  with tempfile.TemporaryDirectory(prefix='clioplay-unihan-') as td:
   path=Path(td)/'Unihan.zip'
   with urllib.request.urlopen(URL,timeout=60) as response:path.write_bytes(response.read())
   pinyin(path)
 if digest(DATA/'pinyin.h')!=json.loads((DATA/'pinyin.json').read_text())['header_sha256']:raise ValueError('Bundled Pinyin data changed; regenerate from pinned Unihan')
 layouts=json.loads((ROOT/'locales/keyboards.json').read_text());langs=json.loads((ROOT/'locales/ui.json').read_text())['languages']
 if [row['language'] for row in layouts['layouts']]!=langs:raise ValueError('Keyboard/UI language IDs must agree')
 rows=[]
 for row in layouts['layouts']:
  text=row['characters']
  if len(set(text))!=len(text) or not text or any(c.isspace() for c in text):raise ValueError('Invalid keyboard layout')
  if any(c!=c.upper() for c in text):raise ValueError('Case-bearing keyboard characters must be capitals')
  name=json.loads((ROOT/'locales/ui.json').read_text())['language_names'][row['language']].upper()
  rows.append(' {'+json.dumps(text,ensure_ascii=False)+','+str(len(text))+','+json.dumps(name,ensure_ascii=False)+'},')
 (DATA/'layouts.h').write_text('/* Generated from locales/keyboards.json. */\nstruct KbdLayout {const char*characters;int count;const char*name;};\nenum {KBD_TEXT_LIMIT='+str(layouts['input_limit'])+'};\nstatic const struct KbdLayout kbd_layouts[]={\n'+'\n'.join(rows)+'\n};\n')
 import build_translations
 translations=build_translations.load()
 with (DATA/'layouts.h').open('a') as f:
  for key in ('Save','Language'):
   values=[key,*translations['strings'][key]]
   f.write('static const char*const kbd_'+key.lower()+'_labels[]={'+','.join(json.dumps(value.upper(),ensure_ascii=False) for value in values)+'};\n')
if __name__=='__main__':main()
