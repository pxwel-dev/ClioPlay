#!/usr/bin/env python3
"""Compile conservative urban fallback profiles from the bundled OSM snapshot.

These are estimates for ordinary cars, never an assertion about posted signs.
Countries with conflicting urban/subnational contexts require local map evidence.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'navigation-builder/tools'))
from global_speeds import CONTEXT


def profiles():
    result = {}
    for key, value in sorted(CONTEXT.items()):
        iso, context = key.split(':', 1)
        if len(iso) != 2 or context != 'urban' or not value[0]:
            continue
        # Configuration-dependent Spanish streets and the differing Welsh
        # restricted-road default cannot be resolved from CPM5 style classes.
        if iso in ('ES', 'GB'):
            continue
        alternatives = [v for k, v in CONTEXT.items()
                        if (k.startswith(iso+':') or k.startswith(iso+'-'))
                        and 'urban' in k.split(':', 1)[1]]
        if all(v == value for v in alternatives):
            result[iso] = value
    return result


def main():
    rows = profiles()
    text = ('/* Generated by tools/build_speed_defaults.py from the bundled OSM\n'
            ' * context snapshot and reviewed exclusions. Estimates only. */\n'
            'static const struct {char iso[3];u8 speed,flags;} urban_defaults[]={\n')
    text += ''.join(' {"%s",%d,%d},\n' % (iso, *value) for iso, value in rows.items())
    text += '};\n'
    (ROOT/'clio843/src/urban_speed_defaults.h').write_text(text)
    print(f'Urban fallback profiles: {len(rows)} countries; conflicting contexts excluded')


if __name__ == '__main__':
    main()
